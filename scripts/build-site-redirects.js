"use strict";
const { fs, path, root, SITE_URL, readJson } = require("./site-utils");
const manifest = readJson(path.join(root, "tmp", "insights-manifest.json"), []);
const sitemap = fs.readFileSync(path.join(root, "sitemap.xml"), "utf8");
const canonicalPaths = [...sitemap.matchAll(/<loc>https?:\/\/[^/]+([^<]*)<\/loc>/g)].map((match) => match[1] || "/");
const issueRoutes = Object.fromEntries(manifest.map((item) => [item.id, item.url]));
const moved = {};
for (const item of manifest) {
  for (const slug of item.redirectSlugs || []) {
    moved[`/insights/${slug}`] = item.url;
    moved[`/insights/${slug}/`] = item.url;
    moved[`/insights/${slug}/index.html`] = item.url;
  }
}
const directories = {};
for (const canonical of canonicalPaths) {
  if (canonical !== "/" && canonical.endsWith("/")) directories[canonical.slice(0, -1)] = canonical;
}
const host = new URL(SITE_URL).hostname;
const source = `// Generated by scripts/build-site-redirects.js.\nfunction q(o){var a=[];if(!o)return\"\";Object.keys(o).sort().forEach(function(k){var x=o[k]||{},v=x.multiValue||[x];v.forEach(function(n){if(n&&n.value!==undefined)a.push(encodeURIComponent(k)+\"=\"+encodeURIComponent(n.value))})});return a.length?\"?\"+a.join(\"&\"):\"\"}\nfunction go(u){return{statusCode:301,statusDescription:\"Moved Permanently\",headers:{location:{value:u},\"cache-control\":{value:\"public, max-age=86400\"}}}}\nfunction handler(e){var r=e.request,u=String(r.uri||\"/\"),h=r.headers&&r.headers.host?r.headers.host.value:\"\",i=${JSON.stringify(issueRoutes)},m=${JSON.stringify(moved)},d=${JSON.stringify(directories)};if(u===\"/insights/post\"||u===\"/insights/post/\"||u===\"/insights/post/index.html\"){var z=r.querystring&&r.querystring.issue?r.querystring.issue.value:\"\";if(i[z])return go(i[z])}var c=u.replace(/\\/{2,}/g,\"/\");if(c===\"/index.html\")c=\"/\";else if(/\\/index\\.html$/.test(c))c=c.slice(0,-10);if(m[c])return go(m[c]);if(d[c])c=d[c];if(c!==u||h===\"www.${host}\")return go(\"${SITE_URL}\"+c+q(r.querystring));return r}\n`;
const out = path.join(root, "cloudfront", "functions", "site-redirects.js");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, source);
const bytes = Buffer.byteLength(source, "utf8");
if (bytes > 10000) throw new Error(`CloudFront Function is ${bytes} bytes; limit is 10,000`);
console.log(`Generated sitewide CloudFront redirects (${bytes} bytes, ${canonicalPaths.length} canonical paths).`);
